"""Validate the inventory snapshot and generate the curated browser catalog."""

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GROUPS = {"rifle": "Rifles", "pistol": "Pistolas", "knife": "Facas", "glove": "Luvas"}
STRING = r'"(?:[^"\\]|\\.)*"'
ROW = re.compile(
    rf"\s*\{{ ({STRING}), ({STRING}), category::(\w+), "
    r"\{ (\d+), (\d+), (\d+), (\d+), ([0-9.]+)f, ([0-9.]+)f \} \},"
)


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_inventory(index, images):
    inventory = {}
    for line in index.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("//"):
            continue
        match = ROW.fullmatch(line)
        if not match:
            raise ValueError(f"Invalid inventory row: {line}")
        weapon, name, group, definition, kit, min_seed, max_seed, minimum, maximum = match.groups()
        pair = int(definition), int(kit)
        if pair in inventory or min(pair) <= 0:
            raise ValueError(f"Duplicate or invalid inventory key: {pair}")
        if not 0 <= float(minimum) <= float(maximum) <= 1 or not 0 <= int(min_seed) <= int(max_seed):
            raise ValueError(f"Invalid inventory limits: {pair}")
        inventory[pair] = {
            "name": json.loads(name), "weapon": json.loads(weapon), "weaponId": pair[0], "kit": pair[1],
            "min": float(minimum), "max": float(maximum), "minSeed": int(min_seed),
            "maxSeed": int(max_seed), "group": GROUPS[group],
        }
    expected = {f"{definition}-{kit}.png" for definition, kit in inventory}
    actual = {image.name for image in images.glob("*.png") if image.is_file()}
    if not expected or expected != actual:
        raise ValueError(f"Preview mismatch. Missing: {sorted(expected - actual)}. Extra: {sorted(actual - expected)}.")
    return inventory


def make_web_catalog(inventory, selection, images):
    finishes = []
    ids = set()
    pairs = set()
    for choice in json.loads(selection.read_text(encoding="utf-8")):
        asset_id = choice["id"]
        pair = (choice["definition"], choice["kit"])
        if not re.fullmatch("[a-z0-9-]+", asset_id) or asset_id in ids or pair in pairs:
            raise ValueError(f"Invalid or duplicate browser entry: {asset_id}")
        if pair not in inventory or not (images / f"{asset_id}.png").is_file():
            raise ValueError(f"Missing inventory pair or browser image: {asset_id}")
        ids.add(asset_id)
        pairs.add(pair)
        finishes.append({"id": asset_id, **inventory[pair],
                         **{key: choice[key] for key in ("rarity", "color", "collection")}})
    return (
        "// Generated by internal/tools/catalog_outputs.py from the inventory and web selection.\n"
        "const finishes = " + json.dumps(finishes, ensure_ascii=False, indent=2) + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify checked-in files without writing")
    args = parser.parse_args()
    index = ROOT / "menu" / "acervo_finishes.inc"
    selection = ROOT / "tools" / "web-collection.json"
    web = ROOT.parent / "ui"
    inventory = read_inventory(index, ROOT / "assets" / "preview")
    generated = make_web_catalog(inventory, selection, web / "assets")
    target = web / "catalog.js"
    if args.check:
        metadata = json.loads((ROOT / "assets" / "catalog-source.json").read_text(encoding="utf-8"))
        if metadata["entries"] != len(inventory) or metadata["index_sha256"] != digest(index):
            raise ValueError("Inventory snapshot metadata is stale")
        if target.read_text(encoding="utf-8") != generated:
            raise ValueError("Browser catalog is stale. Run catalog_outputs.py.")
    else:
        target.write_text(generated, encoding="utf-8")
    print(f"Validated {len(inventory)} inventory finishes and {len(generated.split(chr(10)))} generated browser lines")


if __name__ == "__main__":
    main()
